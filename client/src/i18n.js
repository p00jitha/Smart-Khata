// t('key') or t('key', { n: 5 }). Arrays (chips) are returned as arrays with {vars} filled in.
export const makeT = lang => (key, vars = {}) => {
  const raw = (D[lang] && D[lang][key]) ?? D.en[key] ?? key;
  const fill = s => Object.keys(vars).reduce((acc, k) => acc.split('{' + k + '}').join(vars[k]), s);
  return Array.isArray(raw) ? raw.map(fill) : fill(raw);
};

export const LangCtx = createContext({ lang: 'en', t: makeT('en'), speech: 'en-IN', setLang: () => {} });
export const useLang = () => useContext(LangCtx);